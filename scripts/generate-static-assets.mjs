import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { extname, join, relative } from "node:path";

const APP_DIST = join(process.cwd(), "app", "dist");
const OUTPUT_FILE = join(process.cwd(), "src", "generated", "static-assets.ts");

const CONTENT_TYPES = {
  ".html": "text/html; charset=utf-8",
  ".js": "application/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".json": "application/json; charset=utf-8",
  ".ico": "image/x-icon",
  ".woff2": "font/woff2",
};

function walk(dir, base, out) {
  for (const entry of readdirSync(dir)) {
    const fullPath = join(dir, entry);
    if (statSync(fullPath).isDirectory()) {
      walk(fullPath, base, out);
    } else {
      out.push({ path: "/" + relative(base, fullPath).split("\\").join("/"), file: fullPath });
    }
  }
}

function main() {
  const files = [];
  walk(APP_DIST, APP_DIST, files);

  const entries = files.map(({ path, file }) => {
    const ext = extname(file);
    const contentType = CONTENT_TYPES[ext] ?? "application/octet-stream";
    const isText = [".html", ".js", ".css", ".svg", ".json"].includes(ext);
    const raw = readFileSync(file);
    const value = isText
      ? JSON.stringify(raw.toString("utf-8"))
      : `Uint8Array.from(atob(${JSON.stringify(raw.toString("base64"))}), (c) => c.charCodeAt(0))`;
    return `  ${JSON.stringify(path)}: { contentType: ${JSON.stringify(contentType)}, isText: ${isText}, content: ${value} },`;
  });

  const output = `// AUTO-GENERATED by scripts/generate-static-assets.mjs — do not edit by hand
export type StaticAsset = { contentType: string; isText: boolean; content: string | Uint8Array };

export const staticAssets: Record<string, StaticAsset> = {
${entries.join("\n")}
};
`;

  writeFileSync(OUTPUT_FILE, output, "utf-8");
  console.log(`Generated ${OUTPUT_FILE} with ${files.length} embedded assets`);
}

main();
